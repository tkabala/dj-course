import { PdfDocumentBuilder } from './core/pdfDocumentBuilder'
import { formatDate, formatDateTime, formatEnum } from './core/pdfFormatters'
import type { Document } from '../../model/documents'

export interface PDFOptions {
  includeWatermark?: boolean
  includeFooter?: boolean
}

const DOCUMENT_TYPE_LABELS: Record<Document['type'], string> = {
  contract: 'Contract',
  invoice: 'Invoice',
  registration: 'Vehicle Registration',
  insurance: 'Insurance Policy',
  inspection: 'Technical Inspection Certificate',
  'tir-carnet': 'TIR Carnet',
  adr: 'ADR Certificate',
  'hazmat-permit': 'Hazmat Transport Permit',
  license: 'License',
  certificate: 'Certificate',
  other: 'Document'
}

const ENTITY_TYPE_LABELS: Record<Document['entityType'], string> = {
  vehicle: 'Vehicle',
  customer: 'Customer',
  supplier: 'Supplier',
  driver: 'Driver',
  company: 'Company',
  other: 'Other'
}

export async function generateDocumentPDF(document: Document, options: PDFOptions = {}): Promise<void> {
  const builder = await createDocumentBuilder(document, options)

  builder.sectionTitle('Document Information')
  builder.field('Document Name:', document.name)
  builder.field('Document Type:', getDocumentTypeLabel(document.type))
  builder.field('Document ID:', document.id)

  if (document.number) {
    builder.field('Document Number:', document.number)
  }

  builder.sectionTitle('Related Entity')
  builder.field('Related To:', getEntityTypeLabel(document.entityType))
  builder.field('Entity Name:', document.entityName)
  builder.field('Entity ID:', document.entityId)

  builder.sectionTitle('Important Dates')
  builder.field('Issue Date:', formatDateTime(document.issueDate))

  if (document.expiryDate) {
    builder.field('Expiry Date:', formatDateTime(document.expiryDate))
  }

  builder.field('Created:', formatDateTime(document.createdAt))
  builder.field('Last Updated:', formatDateTime(document.updatedAt))

  if (document.issuingAuthority) {
    builder.sectionTitle('Issuing Authority')
    builder.field('Authority:', document.issuingAuthority)
  }

  if (document.notes) {
    builder.sectionTitle('Notes')
    builder.paragraph(document.notes)
  }

  builder.sectionTitle('Document Content')
  builder.paragraph('This is a sample document generated by the Deliveroo TMS system.')
  builder.paragraph('This document contains all the relevant information as stored in the system.')

  const filename = `${document.name.replace(/[^a-z0-9]/gi, '_').toLowerCase()}_${document.id}.pdf`
  builder.save(filename)
}

