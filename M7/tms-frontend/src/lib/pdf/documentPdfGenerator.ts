function getDocumentTypeLabel(type: Document['type']): string {
  return DOCUMENT_TYPE_LABELS[type] ?? formatEnum(type)
}

function getEntityTypeLabel(type: Document['entityType']): string {
  return ENTITY_TYPE_LABELS[type] ?? formatEnum(type)
}

function createDocumentBuilder(document: Document, options: PDFOptions): Promise<PdfDocumentBuilder> {
  return PdfDocumentBuilder.create({
    title: getDocumentTypeLabel(document.type),
    includeWatermark: options.includeWatermark,
    includeFooter: options.includeFooter !== false,
    drawHeader(builder) {
      const doc = builder.internalDoc
      const pageWidth = builder.pageWidth

      const logoDataUrl = builder.logoDataUrl
      if (logoDataUrl) {
        doc.addImage(logoDataUrl, 'PNG', 20, 10, 40, 15)
      }

      doc.setFontSize(10)
      doc.setFont('helvetica', 'normal')
      doc.text('Transport Management System', pageWidth - 20 - 60, 15)
      doc.text('Deliveroo TMS Sp. z o.o.', pageWidth - 20 - 60, 22)

      doc.setLineWidth(0.5)
      doc.line(20, 30, pageWidth - 20, 30)

      doc.setFontSize(18)
      doc.setFont('helvetica', 'bold')
      doc.text(getDocumentTypeLabel(document.type), 20, 45)

      builder.currentY = 55
    },
    drawFooter(builder) {
      const doc = builder.internalDoc
      const pageWidth = builder.pageWidth
      const pageHeight = builder.pageHeight
      const footerY = pageHeight - 20

      doc.setLineWidth(0.5)
      doc.line(20, footerY - 5, pageWidth - 20, footerY - 5)

      doc.setFontSize(8)
      doc.setFont('helvetica', 'normal')
      doc.text('Generated by Deliveroo TMS', 20, footerY)
      doc.text(`Generated on: ${formatDateTime(new Date())}`, pageWidth - 20 - 50, footerY)
      doc.text(`Page ${doc.getCurrentPageInfo().pageNumber} of ${doc.getNumberOfPages()}`, pageWidth / 2 - 10, footerY)
    }
  })
}
